/**
 * morse_table.c — 数据表摘自硬件设计文档 V1.4 §7.3 与 §8.2
 *
 * 字符表：A–Z + 0–9，堆编号；node 19/21 为 Ü/Ä（不定义），30/31 为空码。
 * LED 表：37 颗灯连续编址 0~36（数字节点不连续，禁止 LED = node - 1）。
 *
 * 【勘误】文档 §8.2 NODE_TO_LED 最后一行（node 56~63）只有 7 个元素，
 * 与 §8.3 映射表及 §7.3 字符表矛盾；本文件按 §8.3 交叉核对后的正确值实现：
 * 56('7')→33、60('8')→34、62('9')→35、63('0')→36，57/58/59/61 无灯。
 * 建议后续修订硬件文档 V1.5 时同步更正。
 */
#include "morse_table.h"

const char MORSE_CHAR[64] = {
    ' ',                                                /* 0 占位 */
    ' ',                                                /* 1 START */
    'E','T','I','A','N','M',                            /* 2-7 */
    'S','U','R','W','D','K','G','O',                    /* 8-15 */
    'H','V','F','?','L','?','P','J',                    /* 16-23 (19=Ü 未定义, 21=Ä 未定义) */
    'B','X','C','Y','Z','Q','?','?',                    /* 24-31 (30/31 空码) */
    '5','4','?','3','?','?','?','2',                    /* 32-39 */
    '?','?','?','?','?','?','?','1',                    /* 40-47 */
    '6','?','?','?','?','?','?','?',                    /* 48-55 */
    '7','?','?','?','8','?','9','0'                     /* 56-63 */
};

const int8_t NODE_TO_LED[64] = {
    -1,                                                 /* 0 */
     0,  1,  2,  3,  4,  5,  6,                         /* 1-7 */
     7,  8,  9, 10, 11, 12, 13, 14,                     /* 8-15 */
    15, 16, 17, -1, 18, -1, 19, 20,                     /* 16-23 (19/21 无灯) */
    21, 22, 23, 24, 25, 26, -1, -1,                     /* 24-31 (30/31 无灯) */
    27, 28, -1, 29, -1, -1, -1, 30,                     /* 32-39 */
    -1, -1, -1, -1, -1, -1, -1, 31,                     /* 40-47 */
    32, -1, -1, -1, -1, -1, -1, -1,                     /* 48-55 (48→32: '6') */
    33, -1, -1, -1, 34, -1, 35, 36                      /* 56-63 (56→33:'7' 60→34:'8' 62→35:'9' 63→36:'0') */
};

char morse_table_char_of_node(uint8_t node)
{
    if (node > NODE_MAX) {
        return '?';
    }
    return MORSE_CHAR[node];
}

int8_t morse_table_led_of_node(uint8_t node)
{
    if (node > NODE_MAX) {
        return -1;
    }
    return NODE_TO_LED[node];
}
